"""Keeps the imported files byte-identical to their upstream commit.

SOURCE.json lists every file this repository took from phibrowser-win: the
upstream path, the local path, the SHA-256 of its bytes, its git mode and its
role. Files are grouped; each group records the upstream commit it came from.

  resync.py verify [--upstream DIR]
      Checks that every listed file exists with the recorded checksum and
      mode, that the managed directories hold no unlisted file and that
      SOURCE.md matches SOURCE.json. With --upstream it also checks each
      recorded checksum against the blob at the recorded commit in that
      phibrowser-win checkout. Exits 1 on any problem.

  resync.py sync --upstream DIR [--commit REV] [--group NAME] [--apply]
      Compares the listed files with REV (default HEAD) of the checkout and
      prints one line per file that is changed, deleted or (inside a group's
      whole-directory trees) added upstream. Dry run unless --apply; --apply
      writes the new bytes, removes deleted files, updates SOURCE.json and
      re-renders SOURCE.md. It refuses to overwrite a local file whose bytes
      differ from the recorded checksum. A pinned group keeps its recorded
      commit and only takes part when named with --group.

  resync.py render
      Rewrites the generated block of SOURCE.md from SOURCE.json.

Only the Python standard library and the git binary are used. Blobs are read
with `git cat-file`, never from the checkout's working tree.
"""

import argparse
import hashlib
import json
import os
import subprocess
import sys

REPO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = "SOURCE.json"
SOURCE_MD = "SOURCE.md"
BEGIN = "<!-- manifest:begin (generated by tools/resync.py render) -->"
END = "<!-- manifest:end -->"


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def load_manifest(repo):
    with open(os.path.join(repo, MANIFEST), encoding="ascii") as f:
        return json.load(f)


def save_manifest(repo, manifest):
    with open(os.path.join(repo, MANIFEST), "w", encoding="ascii") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
        f.write("\n")


def git(upstream, *args):
    return subprocess.run(["git", "-C", upstream, *args], check=True,
                          capture_output=True).stdout


def upstream_tree(upstream, commit):
    """{path: (mode, blob id)} for every file at |commit|."""
    out = git(upstream, "ls-tree", "-r", "-z", commit).decode("utf-8")
    tree = {}
    for record in out.split("\0"):
        if record:
            meta, path = record.split("\t", 1)
            mode, kind, blob = meta.split()
            if kind == "blob":
                tree[path] = (mode, blob)
    return tree


def read_blob(upstream, blob):
    return git(upstream, "cat-file", "blob", blob)


def local_bytes(repo, path):
    try:
        with open(os.path.join(repo, path), "rb") as f:
            return f.read()
    except FileNotFoundError:
        return None


def local_mode(repo, path):
    return "100755" if os.access(os.path.join(repo, path), os.X_OK) \
        else "100644"


def tree_local_path(group, upstream_path):
    """The local path of |upstream_path| if a tree of |group| holds it."""
    for tree in group.get("trees", []):
        if upstream_path.startswith(tree["upstream"]):
            return tree["local"] + upstream_path[len(tree["upstream"]):], tree
    return None, None


def plan(group, tree):
    """[(status, entry)] for |group| against the upstream |tree|.

    status: unchanged, changed, deleted (gone upstream) or added (a new
    upstream file inside one of the group's trees; entry is a new dict).
    """
    result = []
    listed = set()
    for entry in group["files"]:
        listed.add(entry["upstream"])
        if entry["upstream"] not in tree:
            result.append(("deleted", entry))
            continue
        mode, blob = tree[entry["upstream"]]
        same = entry.get("blob") == blob and entry.get("mode") == mode
        result.append(("unchanged" if same else "changed", entry))
    for path in sorted(tree):
        if path in listed:
            continue
        local, holder = tree_local_path(group, path)
        if local:
            result.append(("added", {"upstream": path, "local": local,
                                     "role": holder["role"]}))
    return result


def apply_plan(repo, group, steps, tree, upstream):
    """Writes the changed and added files, removes the deleted ones."""
    problems = []
    for status, entry in steps:
        current = local_bytes(repo, entry["local"])
        if current is not None and "sha256" in entry \
                and sha256(current) != entry["sha256"]:
            problems.append(entry["local"] + ": modified locally, not touched")
    if problems:
        return problems
    files = []
    for status, entry in steps:
        target = os.path.join(repo, entry["local"])
        if status == "deleted":
            if os.path.exists(target):
                os.remove(target)
            continue
        if status != "unchanged" or not os.path.exists(target):
            mode, blob = tree[entry["upstream"]]
            data = read_blob(upstream, blob)
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with open(target, "wb") as f:
                f.write(data)
            os.chmod(target, 0o755 if mode == "100755" else 0o644)
            entry = dict(entry, sha256=sha256(data), mode=mode, blob=blob,
                         lines=data.count(b"\n"))
        files.append(entry)
    group["files"] = sorted(files, key=lambda e: e["local"])
    return []


def verify(repo, manifest, upstream=None):
    """Every way the tree differs from the manifest, as text lines."""
    problems = []
    listed = set()
    for group in manifest["groups"]:
        tree = upstream_tree(upstream, group["commit"]) if upstream else None
        for entry in group["files"]:
            listed.add(entry["local"])
            data = local_bytes(repo, entry["local"])
            if data is None:
                problems.append(entry["local"] + ": missing")
                continue
            if sha256(data) != entry["sha256"]:
                problems.append(entry["local"] + ": checksum differs")
            if local_mode(repo, entry["local"]) != entry["mode"]:
                problems.append(entry["local"] + ": mode differs")
            if tree is None:
                continue
            if entry["upstream"] not in tree:
                problems.append(entry["upstream"] + ": not at upstream "
                                + group["commit"])
            elif sha256(read_blob(upstream, tree[entry["upstream"]][1])) \
                    != entry["sha256"]:
                problems.append(entry["upstream"] + ": upstream blob at "
                                + group["commit"] + " differs")
    for managed in manifest["managed_dirs"]:
        for base, _, names in os.walk(os.path.join(repo, managed)):
            for name in names:
                path = os.path.relpath(os.path.join(base, name), repo)
                if path not in listed:
                    problems.append(path + ": not in " + MANIFEST)
    md = local_bytes(repo, SOURCE_MD)
    if md is not None and md.decode("utf-8") != render(repo, manifest):
        problems.append(SOURCE_MD + ": stale, run tools/resync.py render")
    return problems


def manifest_block(manifest):
    lines = [BEGIN, ""]
    for group in manifest["groups"]:
        files = group["files"]
        lines += [
            "### Group `%s`" % group["name"], "",
            group["description"], "",
            "- Origin: %s" % group["origin"],
            "- Commit: `%s`" % group["commit"],
            "- Commit date: %s" % group["commit_date"],
            "- Pinned: %s" % ("yes" if group.get("pinned") else "no"),
            "- Files: %d, lines: %d" % (
                len(files), sum(e["lines"] for e in files)),
            "",
            "| Local path | Upstream path | Lines | SHA-256 | Role |",
            "|---|---|---:|---|---|"]
        for e in files:
            lines.append("| `%s` | `%s` | %d | `%s` | %s |" % (
                e["local"], e["upstream"], e["lines"], e["sha256"],
                e["role"]))
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def render(repo, manifest):
    """SOURCE.md with its generated block replaced."""
    md = local_bytes(repo, SOURCE_MD)
    text = md.decode("utf-8") if md is not None else BEGIN + "\n" + END + "\n"
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    return head + manifest_block(manifest) + tail


def write_source_md(repo, manifest):
    text = render(repo, manifest)
    with open(os.path.join(repo, SOURCE_MD), "w", encoding="utf-8") as f:
        f.write(text)


def cmd_verify(args):
    problems = verify(args.repo, load_manifest(args.repo), args.upstream)
    for line in problems:
        print(line)
    if problems:
        print("%d problem(s)" % len(problems))
        return 1
    print("ok: every imported file matches " + MANIFEST)
    return 0


def cmd_sync(args):
    manifest = load_manifest(args.repo)
    groups = [g for g in manifest["groups"]
              if (g["name"] == args.group if args.group
                  else not g.get("pinned"))]
    if not groups:
        print("no group to sync")
        return 1
    failed = False
    for group in groups:
        rev = group["commit"] if group.get("pinned") else args.commit
        commit = git(args.upstream, "rev-parse", rev + "^{commit}") \
            .decode().strip()
        tree = upstream_tree(args.upstream, commit)
        steps = plan(group, tree)
        counts = {}
        for status, entry in steps:
            counts[status] = counts.get(status, 0) + 1
            if status != "unchanged":
                print("%-9s %s" % (status, entry["upstream"]))
        print("group %s: %s -> %s: %s" % (
            group["name"], group["commit"][:12], commit[:12],
            ", ".join("%d %s" % (counts[k], k) for k in sorted(counts))))
        if not args.apply:
            continue
        problems = apply_plan(args.repo, group, steps, tree, args.upstream)
        for line in problems:
            print(line)
        if problems:
            failed = True
            continue
        group["commit"] = commit
        group["commit_date"] = git(
            args.upstream, "log", "-1", "--format=%cI", commit).decode().strip()
    if args.apply and not failed:
        save_manifest(args.repo, manifest)
        write_source_md(args.repo, manifest)
        print("applied; now run the build and tests, then commit")
    elif not args.apply:
        print("dry run; pass --apply to refresh the files")
    return 1 if failed else 0


def cmd_render(args):
    write_source_md(args.repo, load_manifest(args.repo))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--repo", default=REPO_DIR,
                        help="this repository (default: the script's)")
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("verify")
    p.add_argument("--upstream", help="a phibrowser-win checkout")
    p.set_defaults(run=cmd_verify)
    p = sub.add_parser("sync")
    p.add_argument("--upstream", required=True,
                   help="a phibrowser-win checkout")
    p.add_argument("--commit", default="HEAD")
    p.add_argument("--group")
    p.add_argument("--apply", action="store_true")
    p.set_defaults(run=cmd_sync)
    p = sub.add_parser("render")
    p.set_defaults(run=cmd_render)
    args = parser.parse_args(argv)
    return args.run(args)


if __name__ == "__main__":
    sys.exit(main())
